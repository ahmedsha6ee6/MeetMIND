import os
from typing import Dict, Any, List
from datetime import date
from docx import Document
from docx.shared import Inches, Pt, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.enum.table import WD_TABLE_ALIGNMENT
from loguru import logger
from app.config import get_settings

settings = get_settings()


class DocumentService:
    def __init__(self):
        self.output_dir = settings.OUTPUT_DIR
        os.makedirs(self.output_dir, exist_ok=True)

    def _get_meeting_dir(self, meeting_id: str) -> str:
        meeting_dir = os.path.join(self.output_dir, str(meeting_id))
        os.makedirs(meeting_dir, exist_ok=True)
        return meeting_dir

    def generate_docx(self, meeting_id: str, title: str, meeting_date: Any, participants: List[str], context: str, mom_data: Dict[str, Any]) -> str:
        """
        Generates an editable, professionally formatted Word DOCX file.
        """
        meeting_dir = self._get_meeting_dir(meeting_id)
        docx_path = os.path.join(meeting_dir, "meeting_minutes.docx")

        doc = Document()

        # Page margins
        sections = doc.sections
        for section in sections:
            section.top_margin = Inches(1.0)
            section.bottom_margin = Inches(1.0)
            section.left_margin = Inches(1.0)
            section.right_margin = Inches(1.0)

        # Title
        title_para = doc.add_paragraph()
        title_run = title_para.add_run(f"Minutes of Meeting: {title}")
        title_run.font.name = "Calibri"
        title_run.font.size = Pt(22)
        title_run.font.bold = True
        title_run.font.color.rgb = RGBColor(23, 38, 60)
        title_para.alignment = WD_ALIGN_PARAGRAPH.LEFT

        # Subtitle
        sub_para = doc.add_paragraph()
        sub_run = sub_para.add_run("Generated by MeetMind AI Assistant")
        sub_run.font.size = Pt(10)
        sub_run.font.italic = True
        sub_run.font.color.rgb = RGBColor(92, 107, 120)

        doc.add_paragraph()  # spacer

        # Metadata Table
        meta_table = doc.add_table(rows=3, cols=2)
        meta_table.alignment = WD_TABLE_ALIGNMENT.CENTER
        meta_table.autofit = True

        rows_data = [
            ("Date:", str(meeting_date)),
            ("Participants:", ", ".join(participants) if participants else "Not specified"),
            ("Context / Agenda:", context if context else "None provided")
        ]

        for i, (label, val) in enumerate(rows_data):
            cell_label = meta_table.cell(i, 0)
            cell_label.paragraphs[0].add_run(label).bold = True
            cell_val = meta_table.cell(i, 1)
            cell_val.paragraphs[0].add_run(val)

        doc.add_paragraph()  # spacer

        # 1. Executive Summary
        self._add_section_heading(doc, "1. Executive Summary")
        summary_text = mom_data.get("summary", "No summary available.")
        doc.add_paragraph(summary_text)

        # 2. Discussion Topics
        topics = mom_data.get("discussion_topics", [])
        if topics:
            self._add_section_heading(doc, "2. Key Discussion Topics")
            for topic in topics:
                doc.add_paragraph(topic, style="List Bullet")

        # 3. Decisions Made
        decisions = mom_data.get("decisions", [])
        if decisions:
            self._add_section_heading(doc, "3. Decisions Made")
            dec_table = doc.add_table(rows=1, cols=2)
            dec_table.alignment = WD_TABLE_ALIGNMENT.CENTER
            hdr = dec_table.rows[0].cells
            hdr[0].paragraphs[0].add_run("Decision Description").bold = True
            hdr[1].paragraphs[0].add_run("Confidence").bold = True

            for d in decisions:
                row = dec_table.add_row().cells
                row[0].paragraphs[0].add_run(d.get("description", ""))
                row[1].paragraphs[0].add_run(d.get("confidence", "explicit").capitalize())

        # 4. Action Items
        actions = mom_data.get("action_items", [])
        if actions:
            self._add_section_heading(doc, "4. Action Items & Assignments")
            act_table = doc.add_table(rows=1, cols=4)
            act_table.alignment = WD_TABLE_ALIGNMENT.CENTER
            hdr = act_table.rows[0].cells
            hdr[0].paragraphs[0].add_run("Task").bold = True
            hdr[1].paragraphs[0].add_run("Owner").bold = True
            hdr[2].paragraphs[0].add_run("Deadline").bold = True
            hdr[3].paragraphs[0].add_run("Confidence").bold = True

            for a in actions:
                row = act_table.add_row().cells
                row[0].paragraphs[0].add_run(a.get("task", ""))
                row[1].paragraphs[0].add_run(a.get("owner") or "Not specified")
                row[2].paragraphs[0].add_run(a.get("deadline") or "Not specified")
                row[3].paragraphs[0].add_run(a.get("confidence", "explicit").capitalize())

        # 5. Open Questions
        questions = mom_data.get("open_questions", [])
        if questions:
            self._add_section_heading(doc, "5. Unresolved Questions & Next Steps")
            for q in questions:
                doc.add_paragraph(q, style="List Bullet")

        doc.save(docx_path)
        logger.info(f"Generated DOCX document at: {docx_path}")
        return docx_path

    def _add_section_heading(self, doc: Document, title: str):
        h = doc.add_paragraph()
        run = h.add_run(title)
        run.bold = True
        run.font.size = Pt(14)
        run.font.color.rgb = RGBColor(22, 135, 131)
        h.paragraph_format.space_before = Pt(12)
        h.paragraph_format.space_after = Pt(4)

    def generate_pdf(self, meeting_id: str, title: str, meeting_date: Any, participants: List[str], context: str, mom_data: Dict[str, Any]) -> str:
        """
        Generates a PDF document via WeasyPrint (F8 fix - lightweight HTML to PDF).
        """
        import weasyprint

        meeting_dir = self._get_meeting_dir(meeting_id)
        pdf_path = os.path.join(meeting_dir, "meeting_minutes.pdf")

        html_content = self._render_html_template(title, meeting_date, participants, context, mom_data)
        weasyprint.HTML(string=html_content).write_pdf(pdf_path)
        logger.info(f"Generated PDF document via WeasyPrint at: {pdf_path}")
        return pdf_path

    def _render_html_template(self, title: str, meeting_date: Any, participants: List[str], context: str, mom_data: Dict[str, Any]) -> str:
        participants_str = ", ".join(participants) if participants else "Not specified"
        context_str = context if context else "None provided"

        # Topics
        topics_html = "".join(f"<li>{t}</li>" for t in mom_data.get("discussion_topics", []))
        if topics_html:
            topics_html = f"<h2>2. Key Discussion Topics</h2><ul>{topics_html}</ul>"

        # Decisions
        decisions = mom_data.get("decisions", [])
        decisions_html = ""
        if decisions:
            rows = "".join(
                f"<tr><td>{d.get('description', '')}</td><td>{d.get('confidence', 'explicit').capitalize()}</td></tr>"
                for d in decisions
            )
            decisions_html = f"""
            <h2>3. Decisions Made</h2>
            <table>
                <thead><tr><th>Decision</th><th>Confidence</th></tr></thead>
                <tbody>{rows}</tbody>
            </table>
            """

        # Action items
        actions = mom_data.get("action_items", [])
        actions_html = ""
        if actions:
            rows = "".join(
                f"<tr><td>{a.get('task', '')}</td><td>{a.get('owner') or '<em>Not specified</em>'}</td><td>{a.get('deadline') or '<em>Not specified</em>'}</td><td>{a.get('confidence', 'explicit').capitalize()}</td></tr>"
                for a in actions
            )
            actions_html = f"""
            <h2>4. Action Items & Assignments</h2>
            <table>
                <thead><tr><th>Task</th><th>Owner</th><th>Deadline</th><th>Confidence</th></tr></thead>
                <tbody>{rows}</tbody>
            </table>
            """

        # Open Questions
        questions_html = "".join(f"<li>{q}</li>" for q in mom_data.get("open_questions", []))
        if questions_html:
            questions_html = f"<h2>5. Unresolved Questions</h2><ul>{questions_html}</ul>"

        return f"""<!DOCTYPE html>
<html>
<head>
<meta charset="utf-8">
<style>
    @page {{
        size: A4;
        margin: 20mm;
    }}
    body {{
        font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, Helvetica, Arial, sans-serif;
        color: #17263C;
        line-height: 1.6;
        font-size: 11pt;
    }}
    h1 {{
        color: #17263C;
        font-size: 20pt;
        margin-bottom: 2px;
    }}
    .subtitle {{
        color: #5C6B78;
        font-size: 9pt;
        margin-top: 0;
        margin-bottom: 20px;
    }}
    .meta-box {{
        background: #F4F6F8;
        border-radius: 6px;
        padding: 12px 16px;
        margin-bottom: 24px;
    }}
    .meta-row {{
        display: flex;
        margin-bottom: 4px;
    }}
    .meta-label {{
        font-weight: bold;
        width: 140px;
        color: #285A7A;
    }}
    h2 {{
        color: #168783;
        font-size: 13pt;
        border-bottom: 1px solid #E1E6EB;
        padding-bottom: 4px;
        margin-top: 22px;
    }}
    table {{
        width: 100%;
        border-collapse: collapse;
        margin-top: 10px;
    }}
    th, td {{
        border: 1px solid #D1D7DC;
        padding: 8px 12px;
        text-align: left;
        font-size: 10pt;
    }}
    th {{
        background-color: #EAF3F3;
        color: #168783;
    }}
    tr:nth-child(even) {{
        background-color: #F9FAFB;
    }}
</style>
</head>
<body>
    <h1>Minutes of Meeting: {title}</h1>
    <div class="subtitle">Generated by MeetMind AI Assistant</div>

    <div class="meta-box">
        <div class="meta-row"><span class="meta-label">Date:</span> <span>{meeting_date}</span></div>
        <div class="meta-row"><span class="meta-label">Participants:</span> <span>{participants_str}</span></div>
        <div class="meta-row"><span class="meta-label">Context / Agenda:</span> <span>{context_str}</span></div>
    </div>

    <h2>1. Executive Summary</h2>
    <p>{mom_data.get('summary', 'No summary available.')}</p>

    {topics_html}
    {decisions_html}
    {actions_html}
    {questions_html}
</body>
</html>
"""


document_service = DocumentService()
